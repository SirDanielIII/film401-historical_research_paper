async () => {
  const results = []
  const wait = (ms = 120) => new Promise(resolve => setTimeout(resolve, ms))
  const check = (name, condition) => { results.push({ name, passed: Boolean(condition) }); if (!condition) throw new Error(name) }
  const click = selector => document.querySelector(selector).click()
  const go = async hash => { location.hash = hash; await wait() }
  const canvasData = () => document.querySelector('.photo-scene').getContext('2d').getImageData(0, 0, 640, 720).data
  try {
    await go('introduction')
    const exit = document.querySelector('.player-close'); if (exit) { exit.click(); await wait() }
    check('seven continuous narrative sections', document.querySelectorAll('.major-section').length === 7)
    check('one compact chapter menu', document.querySelectorAll('nav[aria-label="Exhibit chapters"]').length === 1)
    check('main research visible without clicks', [...document.querySelectorAll('.chapter .research-layout')].every(el => getComputedStyle(el).display !== 'none'))
    check('assignment biography, career, social and political context', ['Raton', 'San Pedro', 'Berkeley', 'Douglas Aircraft', 'Bell Laboratories', 'MGM', 'HUAC', 'Cold War', 'block booking', 'labour'].every(word => document.querySelector('#biography').textContent.includes(word)))
    check('24 questions in seven optional topic groups', document.querySelectorAll('.question-answer').length === 24 && document.querySelectorAll('.question-topic').length === 7)
    check('all source anchors resolve', [...document.querySelectorAll('.citations a')].every(a => document.getElementById(a.hash.slice(1))))
    check('no duplicate element IDs', new Set([...document.querySelectorAll('[id]')].map(el => el.id)).size === document.querySelectorAll('[id]').length)
    document.querySelectorAll('img').forEach(img => img.loading = 'eager')
    await Promise.all([...document.images].map(img => img.decode()))
    check('all 15 historical figures loaded locally', document.querySelectorAll('.media-figure img').length === 15 && [...document.images].every(img => img.naturalWidth && new URL(img.src).origin === location.origin))
    await document.fonts.ready
    check('Berlin regular, demi and bold loaded', ['BRLNSR', 'BRLNSD', 'BRLNSB'].every(name => document.fonts.check(`16px ${name}`)))
    const oldMode = document.querySelector('.vlahos-exhibit').dataset.theme
    click('.theme-toggle'); await wait()
    check('light/dark switch changes theme', document.querySelector('.vlahos-exhibit').dataset.theme !== oldMode)
    click('.theme-toggle'); await wait()
    click('.hero .primary'); await wait()
    check('start presentation uses first chapter without autoplay', document.querySelector('.focused') && document.querySelector('.player-chapter select').value === '1' && !document.querySelector('audio:not([paused])'))
    check('only one persistent player', document.querySelectorAll('.narration-player').length === 1)
    check('missing narration has a usable fallback', document.querySelector('.audio-play').disabled && document.querySelector('.audio-status').textContent.includes('not added'))
    click('.transcript-toggle'); await wait()
    check('transcript is available without recording', document.querySelector('#narration-transcript').textContent.includes('Dick Van Dyke'))
    click('.transcript-toggle'); await wait()
    click('[aria-label="Next narration chapter"]'); await wait()
    check('next goes to biography and pauses', location.hash === '#biography' && document.querySelector('.player-chapter select').value === '2')
    window.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true })); await wait()
    check('keyboard next reaches early effects chapter', location.hash === '#before-vlahos' && document.querySelector('.player-chapter select').value === '3')
    await go('colour-difference')
    check('focused view reuses the same live demo', document.querySelectorAll('.rgb-exhibit').length === 1 && document.querySelector('.focused .photo-scene'))
    if (getComputedStyle(document.querySelector('#colour-difference .research-layout')).display === 'none') click('#colour-difference .focus-research-toggle'); await wait()
    check('research can be restored while presenting', getComputedStyle(document.querySelector('#colour-difference .research-layout')).display !== 'none')
    click('.channel-red'); await wait(200)
    const red = canvasData()
    check('real photographic red channel rendered as grayscale', red[1000] === red[1001] && red[1001] === red[1002] && red.some((v, i) => i % 4 !== 3 && v > 20))
    click('.channel-green'); await wait(200)
    check('green channel differs from red', canvasData()[1000] !== red[1000])
    click('.channel-blue'); await wait(200)
    check('blue view stays grayscale', canvasData()[1000] === canvasData()[1001])
    click('.channel-matte'); await wait(200)
    check('matte has dark backing and retained subject', canvasData()[1000] < 30 && canvasData().some((v, i) => i % 4 !== 3 && v > 240))
    click('.channel-composite'); await wait(200)
    const slider = document.querySelector('[aria-label="Compare poor and better matte"]')
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(slider, '100')
    slider.dispatchEvent(new Event('input', { bubbles: true })); await wait(200)
    const good = canvasData()
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(slider, '0')
    slider.dispatchEvent(new Event('input', { bubbles: true })); await wait(200)
    check('poor/improved comparison changes actual image pixels', canvasData().some((v, i) => v !== good[i]))
    const sample = document.querySelector('[aria-label="Demonstration sample"]')
    sample.value = 'illustration'; sample.dispatchEvent(new Event('change', { bubbles: true })); await wait()
    check('original illustrated edge cases retained', document.querySelector('.rgb-exhibit .scene') && !document.querySelector('.photo-scene'))
    sample.value = 'photo'; sample.dispatchEvent(new Event('change', { bubbles: true })); await wait()
    await go('sodium-vapour')
    for (let i = 0; i < 4; i++) { document.querySelectorAll('.sodium-step-nav button')[i].click(); await wait(); check(`sodium optical step ${i + 1} works`, document.querySelectorAll('.sodium-step-nav button')[i].getAttribute('aria-pressed') === 'true') }
    const sodiumButtons = document.querySelectorAll('.sodium-exhibit > .segmented button')
    sodiumButtons[1].click(); await wait(); check('sodium-lit stage is available', document.querySelector('.sodium-scene').textContent.includes('narrow spectrum'))
    sodiumButtons[2].click(); await wait(); check('sodium final composite is available', document.querySelector('.sodium-scene').textContent.includes('educational example'))
    sodiumButtons[0].click(); await wait()
    window.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' })); await wait()
    check('Escape restores exploration and closes the player', !document.querySelector('.focused') && !document.querySelector('.narration-player'))
    await go('source-S3'); check('citation opens the referenced patent record', document.querySelector('#source-S3').getBoundingClientRect().top > 0)
    check('no page horizontal overflow', document.documentElement.scrollWidth <= document.documentElement.clientWidth)
  } catch (error) { return { passed: results.filter(r => r.passed).length, failed: error.message, results } }
  return { passed: results.length, failed: 0, results }
}
